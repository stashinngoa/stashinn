// Extra breadcrumb labels for pages that aren't top-level nav items
const SUB_PAGE_LABELS: Record<string, string> = {
  notifications: 'Notifications',
  legal: 'Legal Documents',
  locations: 'Locations',
  pocs: 'Points of Contact',
};

const ALL_ITEMS = NAV_SECTIONS.flatMap(s => s.items);

export const isActive = (pathname: string, href: string) =>
  href === '/dashboard' ? pathname === '/dashboard' : pathname === href || pathname.startsWith(`${href}/`);

export function getBreadcrumbs(pathname: string): { label: string; href?: string }[] {
  if (pathname === '/dashboard') return [{ label: 'Overview' }];
  const section = ALL_ITEMS.find(i => i.href !== '/dashboard' && isActive(pathname, i.href));
  const crumbs: { label: string; href?: string }[] = [];
  const rest = section ? pathname.slice(section.href.length).split('/').filter(Boolean) : pathname.split('/').filter(Boolean).slice(1);
  if (section) crumbs.push({ label: section.label, href: rest.length ? section.href : undefined });

  rest.forEach((seg, i) => {
    const isLast = i === rest.length - 1;
    // Dynamic ids (uuids / numbers) are shown as "Details"
    const label = SUB_PAGE_LABELS[seg] ?? (/^[0-9a-f-]{8,}$/i.test(seg) || /^\d+$/.test(seg) ? 'Details' : seg.replace(/-/g, ' ').replace(/^\w/, c => c.toUpperCase()));
    const href = isLast ? undefined : (section?.href ?? '/dashboard') + '/' + rest.slice(0, i + 1).join('/');
    crumbs.push({ label, href });
  });
  return crumbs;
}
